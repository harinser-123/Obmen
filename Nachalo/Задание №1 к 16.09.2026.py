while True:
    
    print("Введите параметры автомобиля по шаблону")
    Выводиввод = input("LADA 2010г 205000км 450000руб ")

    parts = Выводиввод.split()   # разбиваем по пробелам

    if len(parts) != 4:
        print("Ошибка: нужно ввести ровно 4 параметра через пробел.")
        continue
    try:
        данные = {
            "Марка": parts[0],
            "Год": int(parts[1].replace("г", "")),
            "пробег": int(parts[2].replace("км", "")),
            "цена": int(parts[3].replace("руб", ""))
        }
        print(f"Продается автомобиль\nМарка: {данные['Марка']}\nГод выпуска: {данные['Год']}г\nПробег: {данные['пробег']}км\nЦена: {данные['цена']}руб")    
        break
    except ValueError:
            # Если int() не смог превратить текст в число — значит, формат неверный
        print("Ошибка: год, пробег и цена должны быть числами с правильными обозначениями (г, км, руб).")
    except Exception as e:
            # На всякий случай ловим любые другие неожиданные ошибки
        print(f"Произошла непредвиденная ошибка: {e}")
print()

                        











