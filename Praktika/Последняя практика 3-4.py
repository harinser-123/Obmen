s = input()

# Сначала проверяем только форму (как в текущей задаче)
if len(s) == 5 and s[2] == ':' and \
   s[0] in "0123456789" and s[1] in "0123456789" and \
   s[3] in "0123456789" and s[4] in "0123456789":

    # Теперь можно безопасно превратить части в числа
    hours = int(s[0:2])   # берём символы 0 и 1
    minutes = int(s[3:5]) # берём символы 3 и 4

    if 0 <= hours <= 23 and 0 <= minutes <= 59:
        print("Время корректное")
    else:
        print("Некорректное значение времени")
else:
    print("Формат неверный")
