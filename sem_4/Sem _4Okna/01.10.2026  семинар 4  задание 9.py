import tkinter as tk


def main():
    # Создаём главное окно
    root = tk.Tk()

    # Устанавливаем заголовок окна
    root.title("Мой калькулятор")

    # Устанавливаем размер окна (ширина x высота)
    root.geometry("420x320")

    # Добавляем надпись «Привет!»
    label = tk.Label(root, text="Привет!")
    label.pack()  # Размещаем надпись в окне

    # Запускаем главный цикл обработки событий — окно останется открытым
    root.mainloop()


if __name__ == "__main__":
    main()
